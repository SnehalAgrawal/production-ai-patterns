def r17(g):
    d = env(g)
    p = refund("INV-1002", 25, claims=DUPLICATE, reason="duplicate charge PAY-5006")
    d.submit(p)
    d.submit(p)                                      # the assistant's submit was retried
    open_items = [i["id"] for i in d.observe()["items"] if i["status"] == "pending"]
    views = {i: d.view(i) for i in open_items}       # the queue shows every open item
    for i in open_items:
        d.decide(i, "ana", "approve", views[i])
    for i in open_items:
        d.execute(i, "worker-1")
    return d


