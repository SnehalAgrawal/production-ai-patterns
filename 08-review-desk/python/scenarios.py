DATA = Path(__file__).resolve().parent.parent / "data"
POLICY = json.loads((DATA / "policy.json").read_text())
DIRECTORY = json.loads((DATA / "directory.json").read_text())

OCTOBER = "I was charged twice for my October invoice. Please refund the extra charge."


def env(safeguards=SAFEGUARDS):
    clock = FakeClock(POLICY["start"])
    billing = Billing(clock)
    return Desk(clock, billing, copy.deepcopy(DIRECTORY), POLICY, safeguards)


def refund(invoice_id, amount, *, customer="C-1001", conversation="conv-1", requested_by="assistant",
           claims=None, reason="", message=OCTOBER):
    return {"tool": "refund", "customer": customer, "invoice_id": invoice_id, "amount": amount,
            "conversation_id": conversation, "requested_by": requested_by, "claims": claims or {},
            "reason": reason, "customer_message": message}


DUPLICATE = {"duplicate_charge": True}


def approve_and_run(d, item_id, reviewer, **kw):
    out = d.decide(item_id, reviewer, "approve", d.view(item_id), **kw)
    if d.item(item_id)["status"] == "approved":
        d.execute(item_id, "worker-1")
    return out


